/* 
   Ваня принес на кухню рулет, который он хочет разделить с коллегами. 
   Для этого он хочет разрезать рулет на  равных частей. Разумеется, рулет можно резать 
   только поперек. Соотвественно, Костя сделает  разрез ножом через равные промежутки.

    По возвращению с кофе-брейка Ваня задумался — а можно ли было обойтись меньшим числом 
    движений, будь нож Вани бесконечно длинным (иначе говоря, если он мог бы сделать сколько
    угодно разрезов за раз, если эти разрезы лежат на одной прямой)? Считается, что места для
    разрезов намечены заранее, и все разрезы делаются с ювелирной точностью.
    
    Оказывается, что можно. Например, если Ваня хотел бы разделить рулет на  части, он мог 
    бы обойтись двумя разрезами — сначала он разделил бы рулет на две половинки, а потом 
    совместил бы две половинки и разрезал обе пополам одновременно.
    
    Вам дано число , требуется сказать, каким минимальным числом разрезов можно обойтись.
*/
function pieSlice(n) {
  return Math.ceil(Math.log2(n));
}

const readline = require("readline");
const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
});

rl.on("line", (line) => {
  const n = parseInt(line.trim(), 10);
  console.log(pieSlice(n));
  rl.close();
});


