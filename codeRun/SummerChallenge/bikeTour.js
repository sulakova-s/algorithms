/*
  2. Кодерун на летнем велотуре
  
  Кодерун следит за большим летним велотуром, проводящимся в M этапов. После каждого этапа судьи 
  публикуют итоговый протокол — список участников, у которых в этот день изменился общий зачёт, с их
  текущей общей суммой баллов. В одном протоколе каждый участник встречается не более одного раза, и 
  записи в нём идут по возрастанию номеров участников.
  
  Протоколы выходят по ходу тура: самый первый — самый ранний, а последний — самый свежий. 
  Участник попадает в протокол этапа только в том случае, если на этом этапе его общий зачёт 
  изменился, — поэтому в протоколе за день могут присутствовать не все участники.
  
  К финишу необходимо посчитать итоговый общий зачёт: по каждому участнику взять его баллы из самого
  свежего протокола, где он встречается, и вывести всех по возрастанию номера.
  
  Важно: нельзя просто взять последний протокол — в нём перечислены не все участники. Если участника 
  нет в свежем протоколе, его актуальные баллы нужно искать в более ранних. Номер участника может быть нулевым.

  Формат ввода
    В первой строке — число M, количество протоколов.
    Далее идут M протоколов в хронологическом порядке (от раннего к свежему). 
    Каждый протокол задаётся так: 
      строка с числом Li — количество строк в протоколе;
      Li строк, в каждой два числа k и v: номер участника и его баллы в зачёте. 
      Внутри одного протокола номера k
      
  Формат вывода
    Для каждого участника, встретившегося хотя бы в одном протоколе, выведите строку «k v» 
    — номер участника и его балл из самого свежего протокола, где он присутствует. Строки выводите
    по возрастанию k

  Пример:
*/

function listBikeTourScore(input) {
  if (!input?.length) return null;

  let i = 0;
  const M = input[i++];
  if (M <= 0) return null;

  const stats = new Map();

  for (let p = 0; p < M; p++) {
    const Li = input[i++];
    for (let j = 0; j < Li; j++) {
      stats.set(input[i], input[i + 1]);
      i += 2;
    }
  }

  return [...stats.keys()]
    .sort((a, b) => a - b)
    .map((k) => `${k} ${stats.get(k)}`)
    .join("\n");
}

// Тест
console.log(
  listBikeTourScore([
    3, 3, 1, 10, 3, 30, 5, 50, 3, 1, 11, 2, 21, 5, 51, 2, 2, 22, 4, 42,
  ]),
);

// Ввод:
// 3
// 3
// 1 10
// 3 30
// 5 50
// 3
